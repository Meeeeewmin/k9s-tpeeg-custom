#!/bin/sh
set -eu

print_logo() {
  if [ -t 1 ]; then
    printf '\033[38;2;90;210;200m\033[1m%s\033[0m\n' '_______________'
    printf '\033[38;2;90;210;200m\033[1m%s\033[0m\n' '\__   __/  __  \  __________________'
    printf '\033[38;2;90;210;200m\033[1m%s\033[0m\n' '  |   |\    ___/ /  ___/  ___/  ___/'
    printf '\033[38;2;90;210;200m\033[1m%s\033[0m\n' '  |   | \   \   /  __/   __/   __ \ '
    printf '\033[38;2;90;210;200m\033[1m%s\033[0m\n' '  |___|  \___\ /_____/_____/\_____/'
    printf '\n'
  fi
}

print_logo

if [ "$#" -eq 0 ]; then
  exec /bin/k9s --splashless -A
fi

exec /bin/k9s "$@"
